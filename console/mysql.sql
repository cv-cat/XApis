CREATE TABLE IF NOT EXISTS users (
 id VARCHAR(32) PRIMARY KEY, username VARCHAR(40) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL, role VARCHAR(16) NOT NULL,
 disabled TINYINT NOT NULL DEFAULT 0, created DOUBLE NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 token VARCHAR(64) PRIMARY KEY, user_id VARCHAR(32) NOT NULL,
 csrf VARCHAR(128) NOT NULL, expires DOUBLE NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS attempts (`key` VARCHAR(64) PRIMARY KEY, count INT NOT NULL, until DOUBLE NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS account_policies (
 id VARCHAR(32) PRIMARY KEY, owner VARCHAR(32) NOT NULL, x_id VARCHAR(32) NOT NULL,
 first_login DOUBLE NOT NULL, warmup_until DOUBLE NOT NULL, limit_until DOUBLE NOT NULL,
 UNIQUE KEY physical_xid(x_id), FOREIGN KEY(owner) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS accounts (
 id VARCHAR(32) PRIMARY KEY, owner VARCHAR(32) NOT NULL, x_id VARCHAR(64) NOT NULL,
 handle VARCHAR(100) NOT NULL, name VARCHAR(100) NOT NULL, avatar VARCHAR(2048) NOT NULL DEFAULT '',
 secret MEDIUMTEXT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'pending', created DOUBLE NOT NULL,
 warmup_days INT NOT NULL DEFAULT 4, policy_id VARCHAR(32), session_version INT NOT NULL DEFAULT 0,
 cookie_updated DOUBLE, UNIQUE KEY owner_xid(owner,x_id),
 FOREIGN KEY(owner) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(policy_id) REFERENCES account_policies(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ai_settings (
 owner VARCHAR(32) PRIMARY KEY, base_url VARCHAR(1000) NOT NULL, model VARCHAR(100) NOT NULL,
 secret TEXT NOT NULL, instruction TEXT NOT NULL,
 FOREIGN KEY(owner) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sources (
 id VARCHAR(32) PRIMARY KEY, owner VARCHAR(32) NOT NULL, name VARCHAR(100) NOT NULL,
 url TEXT NOT NULL, kind VARCHAR(10) NOT NULL, enabled TINYINT NOT NULL DEFAULT 1,
 last_fetch DOUBLE, error TEXT, created DOUBLE NOT NULL,
 FOREIGN KEY(owner) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS entries (
 id VARCHAR(32) PRIMARY KEY, source_id VARCHAR(32) NOT NULL, title VARCHAR(500) NOT NULL,
 url TEXT NOT NULL, summary MEDIUMTEXT NOT NULL, published DOUBLE, fetched DOUBLE NOT NULL,
 url_hash CHAR(64) GENERATED ALWAYS AS (SHA2(url,256)) STORED,
 UNIQUE KEY source_url(source_id,url_hash),
 FOREIGN KEY(source_id) REFERENCES sources(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rules (
 id VARCHAR(32) PRIMARY KEY, owner VARCHAR(32) NOT NULL, account_id VARCHAR(32) NOT NULL,
 name VARCHAR(100) NOT NULL, source_ids JSON NOT NULL, prompt TEXT NOT NULL, mode VARCHAR(12) NOT NULL,
 interval_minutes INT NOT NULL, daily_limit INT NOT NULL, enabled TINYINT NOT NULL DEFAULT 0,
 next_run DOUBLE NOT NULL, running TINYINT NOT NULL DEFAULT 0, last_run DOUBLE, last_result TEXT, created DOUBLE NOT NULL,
 FOREIGN KEY(owner) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS jobs (
 id VARCHAR(32) PRIMARY KEY, owner VARCHAR(32) NOT NULL, account_id VARCHAR(32) NOT NULL,
 request_id VARCHAR(100) NOT NULL, payload JSON NOT NULL, state VARCHAR(20) NOT NULL,
 scheduled DOUBLE NOT NULL, result JSON NOT NULL DEFAULT (JSON_OBJECT()), error TEXT,
 rule_id VARCHAR(32), created DOUBLE NOT NULL, updated DOUBLE NOT NULL,
 UNIQUE KEY owner_request(owner,request_id), KEY jobs_due(state,scheduled),
 FOREIGN KEY(owner) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE,
 FOREIGN KEY(rule_id) REFERENCES rules(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS publication_ledger (
 id VARCHAR(100) PRIMARY KEY, policy_id VARCHAR(32) NOT NULL, day DATE NOT NULL,
 units INT NOT NULL, confirmed INT NOT NULL DEFAULT 0, state VARCHAR(20) NOT NULL,
 created DOUBLE NOT NULL, updated DOUBLE NOT NULL, KEY daily_posts(policy_id,day),
 FOREIGN KEY(policy_id) REFERENCES account_policies(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rule_entries (
 rule_id VARCHAR(32) NOT NULL, entry_id VARCHAR(32) NOT NULL, PRIMARY KEY(rule_id,entry_id),
 FOREIGN KEY(rule_id) REFERENCES rules(id) ON DELETE CASCADE,
 FOREIGN KEY(entry_id) REFERENCES entries(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS media (
 id VARCHAR(32) PRIMARY KEY, owner VARCHAR(32) NOT NULL, account_id VARCHAR(32) NOT NULL,
 x_id VARCHAR(100) NOT NULL, name VARCHAR(255) NOT NULL, mime VARCHAR(100) NOT NULL, created DOUBLE NOT NULL,
 FOREIGN KEY(owner) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS keyword_groups (
 id VARCHAR(32) PRIMARY KEY, owner VARCHAR(32) NOT NULL, name VARCHAR(100) NOT NULL,
 keywords JSON NOT NULL, created DOUBLE NOT NULL,
 FOREIGN KEY(owner) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS account_maintenance (
 account_id VARCHAR(32) PRIMARY KEY, group_ids JSON NOT NULL DEFAULT (JSON_ARRAY()),
 enabled TINYINT NOT NULL DEFAULT 1, interval_minutes INT NOT NULL DEFAULT 60,
 pages_per_cycle INT NOT NULL DEFAULT 3, delay_min_seconds INT NOT NULL DEFAULT 30,
 delay_max_seconds INT NOT NULL DEFAULT 90, read_comments TINYINT NOT NULL DEFAULT 1,
 comment_pages INT NOT NULL DEFAULT 2, next_run DOUBLE NOT NULL,
 running TINYINT NOT NULL DEFAULT 0, state JSON NOT NULL DEFAULT (JSON_OBJECT()),
 last_run DOUBLE, last_result TEXT, read_count INT NOT NULL DEFAULT 0,
 read_home TINYINT NOT NULL DEFAULT 1, home_pages_per_cycle INT NOT NULL DEFAULT 2,
 FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS maintenance_logs (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, account_id VARCHAR(32) NOT NULL,
 keyword VARCHAR(200) NOT NULL, operation VARCHAR(40) NOT NULL, page INT NOT NULL,
 item_count INT NOT NULL, status VARCHAR(20) NOT NULL, message TEXT NOT NULL,
 created DOUBLE NOT NULL, details JSON NOT NULL DEFAULT (JSON_OBJECT()),
 KEY account_created(account_id,created),
 FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, owner VARCHAR(32), action VARCHAR(100) NOT NULL,
 detail TEXT NOT NULL, created DOUBLE NOT NULL,
 FOREIGN KEY(owner) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS account_logins (
 account_id VARCHAR(32) PRIMARY KEY, stage VARCHAR(30) NOT NULL,
 message VARCHAR(500) NOT NULL, started DOUBLE NOT NULL, updated DOUBLE NOT NULL,
 FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS request_logs (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, account_id VARCHAR(32) NOT NULL,
 attempt_id VARCHAR(32) NOT NULL, method VARCHAR(10) NOT NULL, path VARCHAR(500) NOT NULL,
 status INT, duration_ms INT NOT NULL, request_fields JSON NOT NULL, response_headers JSON NOT NULL,
 response_excerpt TEXT NOT NULL, error_type VARCHAR(100) NOT NULL, created DOUBLE NOT NULL,
 KEY account_time(account_id,created), FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS chat_dispatches (
 account_id VARCHAR(32) NOT NULL, message_id VARCHAR(36) NOT NULL,
 payload_hash VARCHAR(64) NOT NULL, operation VARCHAR(20) NOT NULL,
 state VARCHAR(20) NOT NULL, created DOUBLE NOT NULL, updated DOUBLE NOT NULL,
 PRIMARY KEY(account_id,message_id),
 FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB;
